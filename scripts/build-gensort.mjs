import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const root = process.cwd();
const gensortSourceDir = process.env.GENSORT_SOURCE_DIR
  ? path.resolve(process.env.GENSORT_SOURCE_DIR)
  : path.resolve(root, '..', 'gensort');

if (!fs.existsSync(path.join(gensortSourceDir, 'package.json'))) {
  throw new Error(
    `[build:gensort] Authoritative GenSort source checkout not found at ${gensortSourceDir}. ` +
      `Clone https://github.com/rouguemuse/gensort.git (branch: contextmuse-embedded) to ../gensort or set GENSORT_SOURCE_DIR.`
  );
}

if (!fs.existsSync(path.join(gensortSourceDir, 'node_modules'))) {
  console.log('[build:gensort] Installing dependencies in GenSort source checkout...');
  execSync('npm ci', { stdio: 'inherit', cwd: gensortSourceDir });
}

console.log(`[build:gensort] Building GenSort from ${gensortSourceDir}...`);
execSync('npm run build', { stdio: 'inherit', cwd: gensortSourceDir });

const distDir = path.join(gensortSourceDir, 'dist');
if (!fs.existsSync(path.join(distDir, 'index.html'))) {
  throw new Error('[build:gensort] Expected dist/index.html was not generated by GenSort build');
}

const targetDir = path.join(root, 'cxm_gensort');
const targetAssetsDir = path.join(targetDir, 'assets');
fs.mkdirSync(targetAssetsDir, { recursive: true });

// Remove previous assets in cxm_gensort/assets so stale hashed chunks do not accumulate
for (const file of fs.readdirSync(targetAssetsDir)) {
  fs.rmSync(path.join(targetAssetsDir, file), { recursive: true, force: true });
}

// Copy top-level dist files (index.html, favicon.*, icons.svg, logo.jpg)
for (const entry of fs.readdirSync(distDir, { withFileTypes: true })) {
  if (entry.isFile()) {
    fs.copyFileSync(path.join(distDir, entry.name), path.join(targetDir, entry.name));
  }
}

// Copy dist/assets/* into cxm_gensort/assets/
const distAssetsDir = path.join(distDir, 'assets');
const copiedAssets = [];
for (const file of fs.readdirSync(distAssetsDir)) {
  fs.copyFileSync(path.join(distAssetsDir, file), path.join(targetAssetsDir, file));
  copiedAssets.push(file);
}

console.log(
  `[build:gensort] Synced ${copiedAssets.length} built assets into cxm_gensort/ (${copiedAssets
    .filter((f) => f.endsWith('.js') || f.endsWith('.css'))
    .join(', ')})`
);
